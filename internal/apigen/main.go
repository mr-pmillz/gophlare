package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"slices"
	"strings"

	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
)

type document struct {
	Paths      map[string]map[string]json.RawMessage `json:"paths"`
	Components struct {
		Schemas map[string]schema `json:"schemas"`
	} `json:"components"`
}

type schema struct {
	Ref        string            `json:"$ref"`
	Type       json.RawMessage   `json:"type"`
	Format     string            `json:"format"`
	AnyOf      []schema          `json:"anyOf"`
	Items      *schema           `json:"items"`
	Properties map[string]schema `json:"properties"`
}

type parameter struct {
	Name        string `json:"name"`
	In          string `json:"in"`
	Description string `json:"description"`
	Required    bool   `json:"required"`
	Schema      schema `json:"schema"`
}

type operation struct {
	ID          string      `json:"operationId"`
	Summary     string      `json:"summary"`
	Description string      `json:"description"`
	Parameters  []parameter `json:"parameters"`
	Deprecated  bool        `json:"deprecated"`
	RequestBody *struct {
		Required bool `json:"required"`
		Content  map[string]struct {
			Schema schema `json:"schema"`
		} `json:"content"`
	} `json:"requestBody"`
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by internal/apigen from the Firework specs and oapi-codegen clients. DO NOT EDIT.")
	fmt.Fprintln(&output, "package flareapi")
	fmt.Fprintln(&output, `import (
		"io"
		"net/http"
		"github.com/mr-pmillz/gophlare/flareapi/fireworkv2"
		"github.com/mr-pmillz/gophlare/flareapi/fireworkv3"
		"github.com/mr-pmillz/gophlare/flareapi/fireworkv4"
		openapi_types "github.com/oapi-codegen/runtime/types"
	)`)
	fmt.Fprintln(&output, "var operationDefinitions = []Operation{")
	for _, version := range []string{"v2", "v3", "v4"} {
		if err := generateVersion(&output, version); err != nil {
			return err
		}
	}
	fmt.Fprintln(&output, "}")
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return fmt.Errorf("format registry: %w", err)
	}
	return os.WriteFile("flareapi/operations.gen.go", formatted, 0644)
}

func generateVersion(output *bytes.Buffer, version string) error {
	data, err := os.ReadFile("firework-" + version + "-openapi.json")
	if err != nil {
		return err
	}
	var spec document
	if err := json.Unmarshal(data, &spec); err != nil {
		return err
	}
	generated, err := parser.ParseFile(token.NewFileSet(), "flareapi/firework"+version+"/models.gen.go", nil, 0)
	if err != nil {
		return err
	}
	builders := make(map[string]*ast.FuncDecl)
	for _, declaration := range generated.Decls {
		if function, ok := declaration.(*ast.FuncDecl); ok && function.Recv == nil {
			builders[function.Name.Name] = function
		}
	}
	paths := make([]string, 0, len(spec.Paths))
	for path := range spec.Paths {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	for _, path := range paths {
		var shared []parameter
		if raw := spec.Paths[path]["parameters"]; raw != nil {
			if err := json.Unmarshal(raw, &shared); err != nil {
				return err
			}
		}
		for _, method := range []string{"get", "post", "put", "patch", "delete", "head", "options", "trace"} {
			raw, exists := spec.Paths[path][method]
			if !exists {
				continue
			}
			var endpoint operation
			if err := json.Unmarshal(raw, &endpoint); err != nil {
				return err
			}
			endpoint.Parameters = append(shared[:len(shared):len(shared)], endpoint.Parameters...)
			if err := generateOperation(output, version, method, path, endpoint, spec, builders); err != nil {
				return err
			}
		}
	}
	return nil
}

func generateOperation(output *bytes.Buffer, version, method, path string, endpoint operation, spec document, builders map[string]*ast.FuncDecl) error {
	name := "New" + codegen.ToCamelCaseWithInitialisms(endpoint.ID) + "Request"
	if endpoint.RequestBody != nil {
		name += "WithBody"
	}
	builder, exists := builders[name]
	if !exists {
		for candidate, function := range builders {
			if strings.EqualFold(candidate, name) {
				name, builder = candidate, function
				break
			}
		}
		if builder == nil {
			return fmt.Errorf("%s %s: missing generated builder %s", version, endpoint.ID, name)
		}
	}
	fmt.Fprintf(output, "{Version:%q, ID:%q, Method:%q, Path:%q, Summary:%q, Description:%q, Deprecated:%t,\n",
		version, endpoint.ID, strings.ToUpper(method), path, endpoint.Summary, endpoint.Description, endpoint.Deprecated)
	fmt.Fprintln(output, "Parameters: []Parameter{")
	pageIn := ""
	for _, argument := range endpoint.Parameters {
		kind := spec.kind(argument.Schema)
		itemKind := "string"
		resolved := spec.resolve(argument.Schema)
		if resolved.Items != nil {
			itemKind = spec.kind(*resolved.Items)
		}
		fmt.Fprintf(output, "{Name:%q, In:%q, Type:%q, Format:%q, ItemType:%q, Required:%t, Description:%q},\n",
			argument.Name, argument.In, kind, resolved.Format, itemKind, argument.Required, argument.Description)
		if argument.In == "query" && argument.Name == "from" {
			pageIn = "query"
		}
	}
	fmt.Fprintln(output, "},")
	if endpoint.RequestBody != nil {
		body := endpoint.RequestBody.Content["application/json"].Schema
		if _, exists := spec.resolve(body).Properties["from"]; exists {
			pageIn = "body"
		}
		fmt.Fprintf(output, "HasBody:true, BodyRequired:%t, BodySchema:%q,\n", endpoint.RequestBody.Required, body.Ref)
	}
	fmt.Fprintf(output, "PageIn:%q,\n", pageIn)
	return generateBuilder(output, version, name, endpoint, builder)
}

func generateBuilder(output *bytes.Buffer, version, name string, endpoint operation, builder *ast.FuncDecl) error {
	fmt.Fprintln(output, "build: func(server string, input Request, body io.Reader) (*http.Request, error) {")
	arguments := []string{"server"}
	for _, field := range builder.Type.Params.List[1:] {
		fieldName := field.Names[0].Name
		switch fieldName {
		case "contentType":
			arguments = append(arguments, `"application/json"`)
		case "body":
			arguments = append(arguments, "body")
		case "params":
			typeName := field.Type.(*ast.StarExpr).X.(*ast.Ident).Name
			fmt.Fprintf(output, "params, err := decodeParameters[firework%s.%s](input.Parameters)\nif err != nil { return nil, err }\n", version, typeName)
			arguments = append(arguments, "params")
		default:
			var parameterName string
			for _, argument := range endpoint.Parameters {
				if argument.In == "path" && strings.EqualFold(codegen.ToCamelCaseWithInitialisms(argument.Name), fieldName) {
					parameterName = argument.Name
				}
			}
			if parameterName == "" {
				return fmt.Errorf("%s: no path parameter for %s", name, fieldName)
			}
			var typeName bytes.Buffer
			if err := format.Node(&typeName, token.NewFileSet(), field.Type); err != nil {
				return err
			}
			fmt.Fprintf(output, "%s, err := decodeParameter[%s](input.Parameters, %q)\nif err != nil { return nil, err }\n", fieldName, typeName.String(), parameterName)
			arguments = append(arguments, fieldName)
		}
	}
	fmt.Fprintf(output, "return firework%s.%s(%s)\n},\n},\n", version, name, strings.Join(arguments, ", "))
	return nil
}

func (spec document) resolve(value schema) schema {
	for depth := 0; depth < 32; depth++ {
		if value.Ref != "" {
			value = spec.Components.Schemas[strings.TrimPrefix(value.Ref, "#/components/schemas/")]
			continue
		}
		if len(value.AnyOf) > 0 {
			for _, candidate := range value.AnyOf {
				if string(candidate.Type) != `"null"` {
					value = candidate
					break
				}
			}
			continue
		}
		break
	}
	return value
}

func (spec document) kind(value schema) string {
	value = spec.resolve(value)
	var kind string
	if json.Unmarshal(value.Type, &kind) == nil && kind != "" {
		return kind
	}
	var kinds []string
	if json.Unmarshal(value.Type, &kinds) == nil {
		for _, candidate := range kinds {
			if candidate != "null" {
				return candidate
			}
		}
	}
	return "string"
}
